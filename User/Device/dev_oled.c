uint8_t dev_oled_init(void)
{
	/* 检查设备是否在线 */
	if(HAL_I2C_IsDeviceReady(&hi2c1, OLED_I2C_ADDR, 3, 100) != HAL_OK)
	{
		return 1;
	}
	// 标准SSD1306初始化命令
	dev_oled_write_cmd(0xAE); 						// 关闭显示
	dev_oled_write_cmd(0xD5); dev_oled_write_cmd(0x80); // 设置时钟分频
	dev_oled_write_cmd(0xA8); dev_oled_write_cmd(0x3F); // 设置多路复用率
	dev_oled_write_cmd(0xD3); dev_oled_write_cmd(0x00); // 设置显示偏移
	dev_oled_write_cmd(0x40); 						// 设置起始行
	dev_oled_write_cmd(0x8D); dev_oled_write_cmd(0x14); // 使能电荷泵
	dev_oled_write_cmd(0x20); dev_oled_write_cmd(0x00); // 设置内存寻址模式
	dev_oled_write_cmd(0xA1); 						// 设置段重映射
	dev_oled_write_cmd(0xC8); 						// 设置COM扫描方向
	dev_oled_write_cmd(0xDA); dev_oled_write_cmd(0x12); // 设置COM引脚配置
	dev_oled_write_cmd(0x81); dev_oled_write_cmd(0xCF); // 设置对比度
	dev_oled_write_cmd(0xD9); dev_oled_write_cmd(0xF1); // 设置预充电周期
	dev_oled_write_cmd(0xDB); dev_oled_write_cmd(0x40); // 设置VCOMH
	dev_oled_write_cmd(0xA4); 						// 恢复显示内容
	dev_oled_write_cmd(0xA6); 						// 正常显示(非反色)
	dev_oled_write_cmd(0xAF); 						// 开启显示

	dev_oled_clear(); // 清屏
	return 0;
}

void dev_oled_clear(void)
{
	/* 优化:用缓冲区一次性将一页内的所有列写0,降低传输次数,防止拖慢系统 */
	uint8_t buf[129];
	buf[0] = 0x40;                  			/* 控制字节:后续是数据 */
	for (uint8_t i = 1; i < 129; i++) {
		buf[i] = 0x00;
	}
	for(uint8_t page = 0; page < 8; page ++)
	{
		dev_oled_write_cmd(0xB0 + page);
		dev_oled_write_cmd(0x00);				// 设置列地址低4位
		dev_oled_write_cmd(0x10);				// 设置列地址高4位
		HAL_I2C_Master_Transmit(&hi2c1,OLED_I2C_ADDR,buf,129,100);

	}
}

void dev_oled_show_string(uint8_t x, uint8_t y, const char *str)
{
	static uint8_t buf[129];                   /* 0x40 + 128 字节数据 */
	uint8_t page = y / 8;
	uint8_t max_cols = (uint8_t)((128U - x) / 8U);   /* 这一行能放下几个字 */
	uint8_t cols = 0;

	/* 先数出要写几个字符 */
	while (str[cols] != '\0' && cols < max_cols) { cols ++; }

	/* 上下两页各发一次 */
	for (uint8_t half = 0; half < 2; half++)
	{
		buf[0] = 0x40;	/* 控制字节 */

		/* 先把上半页横排填满,再填下一页 */
		for (uint8_t char_pos = 0; char_pos < max_cols; char_pos++)
		{
			/* 不够,补空格 */
			char ch = (char_pos < cols) ? str[char_pos] : ' ';
			uint8_t idx = dev_oled_get_index(ch);
			for (uint8_t byte_pos = 0; byte_pos < 8; byte_pos++)
			{
				buf[1 + char_pos * 8 + byte_pos] = Font8x16[idx][half * 8 + byte_pos];
			}
		}

		/* 定位到这一页的行首,然后一次把 128 字节全部推出去 */
		dev_oled_write_cmd(0xB0 + page + half);
		dev_oled_write_cmd(0x00 | (x & 0x0F));
		dev_oled_write_cmd(0x10 | ((x >> 4) & 0x0F));
		HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 129, 100);
	}
}
/* Private functions ---------------------------------------------------------*/
static void dev_oled_write_cmd(uint8_t cmd)
{
	/* 控制字节0x00 + 命令 */
	uint8_t buf[2] = {0x00,cmd};
	HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, 100);
}
